import assert from 'node:assert/strict';
import { once } from 'node:events';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';
import { chromium } from 'playwright';
import { createPreviewServer } from '../scripts/serve.js';

test('Emberfall .npt loads, moves, collides, saves, restores and fights in a real browser', { timeout: 40_000 }, async t => {
    const server = await createPreviewServer(fileURLToPath(new URL('../', import.meta.url)));
    server.listen(0, '127.0.0.1'); await once(server, 'listening');
    t.after(() => new Promise(resolve => server.close(resolve)));
    const browser = await chromium.launch({ headless: true });
    t.after(() => browser.close());
    const page = await browser.newPage({ viewport: { width: 1100, height: 740 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    await page.goto(`http://127.0.0.1:${server.address().port}/examples/emberfall/`);
    await page.getByRole('button', { name: 'Play Game' }).click();
    await page.waitForFunction(() => window.game?.scene?.children?.filter(e => e.gameplay).length === 4);
    await page.locator('#emberfall-hud').waitFor();
    const position = () => page.evaluate(() => ({ ...window.game.scene.children.find(e => e.id === 'hero').components.find(c => c.constructor.name === 'Transform').position }));
    const hold = async (key, ms) => { await page.keyboard.down(key); await page.waitForTimeout(ms); await page.keyboard.up(key); await page.waitForTimeout(80); };
    const start = await position();
    await hold('d', 250); assert.ok((await position()).x > start.x + 0.2);
    await hold('s', 250); assert.ok((await position()).y > start.y + 0.2);
    await hold('a', 1000); assert.ok((await position()).x >= 1.32, 'west wall remains solid');
    await page.keyboard.press('o'); await page.getByText('Saved to slot 1.').waitFor();
    const saved = await position(); await hold('d', 300);
    await page.keyboard.press('l'); await page.getByText('Loaded slot 1.').waitFor();
    const restored = await position(); assert.ok(Math.abs(saved.x - restored.x) < 0.02);
    await hold('d', 1400);
    await page.keyboard.down('j'); await hold('d', 1000); await page.waitForTimeout(2200); await page.keyboard.up('j');
    const health = await page.evaluate(() => window.game.scene.children.filter(e => e.gameplay && e.id !== 'hero').map(e => e.gameplay.combatant.health));
    assert.ok(health.some((value, index) => value < [50, 50, 100][index]), 'ordinary attack input damages a guardian');
    await page.reload(); await page.getByRole('button', { name: 'Play Game' }).click();
    await page.waitForFunction(() => window.game.scene.children.filter(e => e.gameplay).length === 4);
    await page.keyboard.press('l'); await page.getByText('Loaded slot 1.').waitFor();
    assert.ok(Math.abs((await position()).x - saved.x) < 0.02, 'saved position survives full runtime restart');
    await page.evaluate(() => window.game.resetProject());
    assert.equal(await page.locator('#emberfall-hud').count(), 0, 'scene disposal removes project UI');
    assert.deepEqual(errors, []);
});
