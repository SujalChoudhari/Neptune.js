/**
 * Create an SVG icon element
 * @param {string} name - Icon name from ICONS
 * @param {object} options - Size, color, class options
 */
export function icon(name, options = {}) {
    const { size = 16, color = 'currentColor', className = '' } = options;
    const path = ICONS[name];

    if (!path) {
        console.warn(`Icon "${name}" not found`);
        return '';
    }

    return `<svg class="icon ${className}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${path}</svg>`;
}

/**
 * Create a clickable icon button
 */
export function iconButton(iconName, options = {}) {
    const { title = '', onClick = '', className = '', disabled = false } = options;
    const iconSvg = icon(iconName, { size: options.size || 18 });

    return `<button class="icon-btn ${className}" title="${title}" ${disabled ? 'disabled' : ''} ${onClick ? `onclick="${onClick}"` : ''}>${iconSvg}</button>`;
}

/**
 * IconManager - Runtime icon helpers
 */
export class IconManager {
    /**
     * Replace all [icon:name] placeholders in HTML
     */
    static replaceIconPlaceholders(html) {
        return html.replace(/\[icon:(\w+)\]/g, (match, name) => icon(name));
    }

    /**
     * Add icon to existing element
     */
    static addIconToElement(element, iconName, position = 'prepend') {
        const iconHtml = icon(iconName);
        if (position === 'prepend') {
            element.insertAdjacentHTML('afterbegin', iconHtml);
        } else {
            element.insertAdjacentHTML('beforeend', iconHtml);
        }
    }

    /**
     * Create icon element (returns DOM element)
     */
    static createElement(iconName, options = {}) {
        const temp = document.createElement('div');
        temp.innerHTML = icon(iconName, options);
        return temp.firstChild;
    }
}
